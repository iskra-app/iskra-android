package wtf.iskra.core.session

/**
 * Что о вас узнают другие, пока вы ничего не пишете: что вы в сети и что печатаете. Порт `PrivacySettings`.
 *
 * Читается в момент, когда это важно, — нажатие клавиши, возвращение на передний план. Оба выключены по умолчанию, как в любом
 * мессенджере: спрятаться — выбор, который делают, а не который делают за человека.
 *
 * Скрыв своё «был(а)», вы не видите и чужие, как в Telegram ([seesOthersPresence]). Скрытое «печатает…» чужие не скрывает: сервер,
 * что пересылает набор, не спрашивает разрешения у читающего.
 */
data class PrivacySettings(
    /** Сообщает ли аккаунт серверу, что он не в сети, чем бы ни занимался, — чтобы никто не видел, когда он был здесь последний раз. */
    val hidesPresence: Boolean = HIDES_PRESENCE_BY_DEFAULT,
    /** Остаётся ли набор сообщения между вами и полем ввода. */
    val hidesTyping: Boolean = HIDES_TYPING_BY_DEFAULT,
) {
    /**
     * Спрашивает ли приложение сервер, где другие. Никогда, пока своё скрыто: следить за людьми, прячась от них, — единственное
     * сочетание, что переключатель исключает, и исключает здесь, а не в экране, который мог бы забыть.
     */
    val seesOthersPresence: Boolean get() = !hidesPresence

    companion object {
        const val HIDES_PRESENCE_BY_DEFAULT = false
        const val HIDES_TYPING_BY_DEFAULT = false
    }
}
